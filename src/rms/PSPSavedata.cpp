void pspSilentSave(const std::vector<int8_t>& buf)
{
    std::string saveDir = "ms0:/PSP/SAVEDATA/GDEF01224";
    sceIoMkdir(saveDir.c_str(), 0777);

    // Write PARAM.SFO
    {
        SceUID fd = sceIoOpen((saveDir + "/PARAM.SFO").c_str(), PSP_O_WRONLY | PSP_O_CREAT | PSP_O_TRUNC, 0777);
        if (fd >= 0) {
            sceIoWrite(fd, sfo_data, sizeof(sfo_data));
            sceIoClose(fd);
        }
    }

    // Write ICON0.PNG
    bool icon_written = false;
    try {
        auto fs = cmrc::assets::get_filesystem();
        auto icon_file = fs.open("ICON0.png"); // WHENCE assets strips the assets/ prefix
        SceUID fd = sceIoOpen((saveDir + "/ICON0.PNG").c_str(), PSP_O_WRONLY | PSP_O_CREAT | PSP_O_TRUNC, 0777);
        if (fd >= 0) {
            if (icon_file.size() > 0) {
                sceIoWrite(fd, icon_file.begin(), icon_file.size());
                icon_written = true;
            }
            sceIoClose(fd);
        }
    } catch(...) {}

    if (!icon_written) {
        // Fallback: try reading from the local disk path if CMRC throws
        SceUID fd_in = sceIoOpen("assets/ICON0.png", PSP_O_RDONLY, 0777);
        if (fd_in >= 0) {
            SceOff size = sceIoLseek(fd_in, 0, PSP_SEEK_END);
            sceIoLseek(fd_in, 0, PSP_SEEK_SET);
            if (size > 0) {
                std::vector<uint8_t> tmp_buf(size);
                sceIoRead(fd_in, tmp_buf.data(), size);

                SceUID fd_out = sceIoOpen((saveDir + "/ICON0.PNG").c_str(), PSP_O_WRONLY | PSP_O_CREAT | PSP_O_TRUNC, 0777);
                if (fd_out >= 0) {
                    sceIoWrite(fd_out, tmp_buf.data(), size);
                    sceIoClose(fd_out);
                }
            }
            sceIoClose(fd_in);
        }
    }

    // Write DATA.BIN atomically
    if(!buf.empty()) {
        std::string tmpFile = saveDir + "/DATA.BIN.tmp";
        std::string finalFile = saveDir + "/DATA.BIN";
        SceUID fd = sceIoOpen(tmpFile.c_str(), PSP_O_WRONLY | PSP_O_CREAT | PSP_O_TRUNC, 0777);
        if (fd >= 0) {
            sceIoWrite(fd, buf.data(), buf.size());
            sceIoClose(fd);
            sceIoRemove(finalFile.c_str());
            sceIoRename(tmpFile.c_str(), finalFile.c_str());
        }
    }
}
